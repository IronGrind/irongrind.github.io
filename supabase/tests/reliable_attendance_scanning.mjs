import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { randomUUID } from 'node:crypto';
const { PGlite } = await import(pathToFileURL(process.argv[2]).href);
const db = new PGlite();
const staff = randomUUID(), admin = randomUUID(), memberUser = randomUUID(), member = randomUUID(), session = randomUUID();
try {
    await db.exec(`
        create role anon; create role authenticated;
        create schema auth; create schema private;
        create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
        create table auth.users(id uuid primary key);
        create table profiles(id uuid primary key, role text, is_active boolean);
        create table members(id uuid primary key, auth_user_id uuid, username text, full_name text, expiry_date date, end_date date);
        create table attendance(id uuid primary key default gen_random_uuid(), member_id uuid references members(id), time_in timestamptz, time_out timestamptz, recorded_by uuid);
        create table mobile_attendance_scan_sessions(id uuid primary key, token_hash text, expires_at timestamptz, paired_at timestamptz);
        insert into auth.users values ('${staff}'), ('${admin}'), ('${memberUser}');
        insert into profiles values ('${staff}','staff',true), ('${admin}','admin',true), ('${memberUser}','member',true);
        insert into members values ('${member}','${memberUser}','member_one','Member One',current_date+30,null);
        insert into mobile_attendance_scan_sessions values ('${session}',md5('secret'),now()+interval '30 days',now());
        grant usage on schema auth to authenticated;
    `);
    const migration = await readFile(new URL('../migrations_archive/pre-baseline-20261105/20261104000026_reliable_attendance_scanning.sql', import.meta.url), 'utf8');
    await db.exec(migration);
    await db.exec(migration);
    const login = async id => db.query("select set_config('request.jwt.claim.sub',$1,false)", [id]);
    const scan = async (request = randomUUID(), token = 'secret') => (await db.query('select record_attendance_scan($1,$2,$3,$4) as result', [`IRONGRIND|${member}`, request, session, token])).rows[0].result;
    await login(staff);
    await db.exec('set role authenticated');
    const request = randomUUID();
    assert.equal((await scan(request)).action, 'check_in');
    assert.equal((await scan(request)).action, 'check_in', 'Retry returns original result');
    assert.equal((await scan()).action, 'duplicate', 'Rapid second scan cannot check member out');
    await db.exec('reset role');
    assert.equal((await db.query('select count(*)::int as n from attendance')).rows[0].n, 1);
    assert.equal((await db.query('select recorded_by from attendance')).rows[0].recorded_by, staff);
    await db.exec("update attendance set time_in=now()-interval '1 hour'; update members set expiry_date=current_date-1");
    await login(admin);
    assert.equal((await scan()).action, 'check_out', 'Expired member can still leave');
    assert.equal((await db.query('select checked_out_by from attendance')).rows[0].checked_out_by, admin);
    await db.exec("update attendance set time_out=now()-interval '10 minutes'");
    await assert.rejects(scan(), /Membership is expired/);
    await db.exec('update members set expiry_date=current_date+30');
    await assert.rejects(scan(randomUUID(), 'wrong'), /pairing is invalid or expired/);
    await db.exec("update mobile_attendance_scan_sessions set expires_at=now()-interval '1 second'");
    await assert.rejects(scan(), /pairing is invalid or expired/);
    await login(memberUser);
    await assert.rejects(scan(), /Active staff or admin/);
    await login(staff);
    await db.exec(`update profiles set is_active=false where id='${staff}'`);
    await assert.rejects(scan(), /Active staff or admin/);
    await db.exec('set role anon');
    await assert.rejects(scan(), /permission denied/);
    await db.exec('reset role');
    await assert.rejects(db.query('select submit_mobile_attendance_scan($1,$2,$3)', [session,'secret','QR']), /Update the attendance app/);
    console.log('Passed: migration rerun, operator attribution, check-out attribution, safe retries, rapid duplicate protection, expiry, pairing validity, inactive/member/anonymous isolation.');
} finally { await db.close(); }
