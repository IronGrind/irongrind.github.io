import assert from 'node:assert/strict';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const { PGlite }=await import(pathToFileURL(process.argv[2]).href);
const db=new PGlite();
const user='11111111-1111-4111-8111-111111111111',other='22222222-2222-4222-8222-222222222222';
const old='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',fresh='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb',third='cccccccc-cccc-4ccc-8ccc-cccccccccccc';
try {
    await db.exec(`create role anon; create role authenticated; create role service_role; create role authenticator;
      create schema auth; create schema private; grant usage on schema auth to anon,authenticated; grant usage on schema private to authenticated;
      create function auth.jwt() returns jsonb language sql as $$select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb$$;
      create function auth.uid() returns uuid language sql as $$select (auth.jwt()->>'sub')::uuid$$;
      create function auth.role() returns text language sql as $$select auth.jwt()->>'role'$$;
      create table auth.users(id uuid primary key);
      insert into auth.users values('${user}'),('${other}');
      create table auth.sessions(id uuid primary key,user_id uuid,created_at timestamptz,not_after timestamptz);
      insert into auth.sessions values('${old}','${user}',now()-interval '2 minutes',null),('${fresh}','${user}',now()-interval '1 minute',null),('${third}','${other}',now(),null);
      create table public.protected_records(id integer);
      insert into protected_records values(1);
      alter table protected_records enable row level security;
      grant select,insert on protected_records to authenticated;
      create policy existing_access on protected_records to authenticated using(true) with check(true);
      create function public.previous_hook() returns void language plpgsql as $$begin perform set_config('test.previous_hook','called',false); end$$;
      alter role authenticator set pgrst.db_pre_request='public.previous_hook';`);
    const sql=fs.readFileSync('supabase/migrations/20261108000003_single_account_session.sql','utf8');
    await db.exec(sql); await db.exec(sql);
    const fix=fs.readFileSync('supabase/migrations/20261108000004_anonymous_session_guard.sql','utf8');
    await db.exec(fix); await db.exec(fix);
    await db.exec("select set_config('request.jwt.claims','{\"role\":\"anon\"}',false); set role anon; select enforce_account_session(); reset role;");
    const login=async(uid,sid)=>{
      await db.exec('reset role');
      await db.query("select set_config('request.jwt.claims',$1,false)",[JSON.stringify({sub:uid,session_id:sid,role:'authenticated'})]);
      await db.exec('set role authenticated');
    };
    const active=async()=>(await db.query('select current_account_session_is_active() as active')).rows[0].active;
    await login(user,old); assert.equal(await active(),true,'Existing sessions work before a replacement login');
    await db.query('select activate_account_session()');
    await login(user,fresh); await db.query('select activate_account_session()');
    assert.equal(await active(),true);
    await db.exec("select set_config('request.path','/protected_records',false)");
    await db.exec('select enforce_account_session()');
    assert.equal((await db.query("select current_setting('test.previous_hook') as value")).rows[0].value,'called');
    await login(user,old); assert.equal(await active(),false);
    assert.equal((await db.query('select * from protected_records')).rows.length,0,'RLS blocks replaced session');
    await assert.rejects(db.exec('insert into protected_records values(2)'),/row-level security/);
    await assert.rejects(db.exec('select enforce_account_session()'),/ACCOUNT_SESSION_REPLACED/);
    await assert.rejects(db.exec('select activate_account_session()'),/ACCOUNT_SESSION_REPLACED/);
    await db.exec("select set_config('request.path','/rpc/current_account_session_is_active',false)");
    await db.exec('select enforce_account_session()');
    await login(other,third); await db.exec('select activate_account_session()'); assert.equal(await active(),true);
    await db.exec('reset role'); await db.query('delete from auth.sessions where id=$1',[fresh]);
    await login(user,old); assert.equal(await active(),false,'Signing out the latest device never restores older sessions');
    await login(user,third); await assert.rejects(db.exec('select activate_account_session()'),/ACCOUNT_SESSION_REPLACED/);
    console.log('Passed: new login replaces old, old sessions cannot reclaim, profile/table access blocked, old RPCs denied, previous API hook preserved, other users unaffected, and sign-out never restores an old session.');
} finally { await db.close(); }
